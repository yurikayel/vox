/** @file Vox client entry — boot and route wiring. */
import { initColorMode } from "./color-mode.js";
import { applySkyTheme, initSkyTheme } from "./sky-theme.js";
import * as demoSeed from "./demo-seed.js";
import { loadRemoteFlags } from "./feature-flags.js";
import { installDomDelegates } from "./app/dom-delegates.js";
import { attachReportHandlers } from "./app/report-flow.js";
import { wireRoute, setupHashchangeListener, routeImpl as route } from "./app/route.js";
import { installEntryGuards, hasFullEntry } from "./app/onboarding.js";
import { initDmListeners, initGossipListeners, initSocialInteractions } from "./app/init.js";
import { initPostMediaLightbox } from "./app/post-media-lightbox.js";
import { watchFrameCards } from "./app/frame-ui.js";
import { attachPostMoreMenuHandlers } from "./app/post-more-menu.js";
import { attachProfileNoteHandlers } from "./app/profile-note-ui.js";
import { attachPhotoTagUi } from "./app/photo-tag-ui.js";
import { attachExplodeHandlers } from "./explode-dispatch.js";
import { attachQrUrlHandlers } from "./qr-url.js";
import { attachPostOverlayActionMenuHandlers } from "./app/screens-home.js";
import { attachQuarantineHandlers } from "./app/context.js";
import { syncIdentity } from "./app/screens-network.js";
import { startDmOutbox } from "./app/dm-wire.js";
import { attachChannelHandlers } from "./app/community-channel-flow.js";
import { startVoxLinks } from "./app/vox-link-flow.js";
import { startVaultMigration } from "./vault/index.js";
import { startKeysAtRest } from "./identity/index.js";
import { showDueInboxBackup } from "./app/inbox-backup-ui.js";
import { startStorageDurability } from "./app/storage-durability-flow.js";
import { startAccountExitBanner } from "./app/account-exit-banner.js";
import { startMeshVault } from "./app/mesh-vault-ui.js";
import { setNaturalHideLoader } from "./moderation.js";
import { startRehearsalBanner } from "./rehearsal-mode.js";

void startKeysAtRest().catch(() => {});
installDomDelegates(document);
startRehearsalBanner();
// PM-83: a base (moderation.js) não importa app/; o fluxo do moderador natural entra por aqui, sob demanda.
setNaturalHideLoader(async (communityId, modActions) => {
  const flow = await import("./app/natural-mod-flow.js");
  return flow.naturalModLabOn() ? flow.loadNaturalHideActions(communityId, modActions) : [];
});
attachReportHandlers(document);
attachChannelHandlers(document);
installEntryGuards();
initColorMode(document, { onApply: () => applySkyTheme(document) });
initSkyTheme();
wireRoute();
setupHashchangeListener();
initDmListeners();
startDmOutbox();
void startVoxLinks().catch(() => {});
initGossipListeners();
watchFrameCards(document);
void startVaultMigration().catch(() => {});
initSocialInteractions();
initPostMediaLightbox();
attachPostMoreMenuHandlers();
attachProfileNoteHandlers();
attachPhotoTagUi();
attachExplodeHandlers();
attachQrUrlHandlers();
attachPostOverlayActionMenuHandlers();
attachQuarantineHandlers();
syncIdentity();
Promise.allSettled([loadRemoteFlags(), demoSeed.purgeMockDemoSeed()]).finally(() => {
  route();
  setTimeout(() => void showDueInboxBackup(), 3000);
  void startStorageDurability({ hasAccount: hasFullEntry }).catch(() => {});
  void startAccountExitBanner({ hasAccount: hasFullEntry }).catch(() => {});
  startMeshVault({ hasAccount: hasFullEntry });
});
