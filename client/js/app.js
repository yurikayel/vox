installEntryGuards();
initColorMode(document, { onApply: () => applySkyTheme(document) });
initSkyTheme();
wireRoute();
setupHashchangeListener();
initDmListeners();
startDmOutbox();
void startVoxLinks().catch(() => {});
initGossipListeners();
void startVaultMigration().catch(() => {});
initSocialInteractions();
initPostMediaLightbox();
attachPostMoreMenuHandlers();
attachProfileNoteHandlers();
attachPhotoTagUi();
attachExplodeHandlers();
attachQrUrlHandlers();
attachPostOverlayActionMenuHandlers();
attachQuarantineHandlers();
syncIdentity();
Promise.allSettled([loadRemoteFlags(), demoSeed.purgeMockDemoSeed()]).finally(() => {
  route();
  setTimeout(() => void showDueInboxBackup(), 3000);
  void startStorageDurability({ hasAccount: hasFullEntry }).catch(() => {});
  void startAccountExitBanner({ hasAccount: hasFullEntry }).catch(() => {});
});
